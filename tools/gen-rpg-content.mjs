// Exports the web prototype's RPG content tables (quests, dialogues, locations) as JSON into a C# file,
// Assets/_Cypher/Scripts/Core/Rpg/RpgContent.g.cs. Run once to port the content; after that the C# file is ours and is edited by hand
// (re-running overwrites it). Read-only against the prototype.
//
//   node tools/gen-rpg-content.mjs <path-to-cyberpunkish>
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const protoRoot = resolve(process.argv[2] ?? '');
if (!process.argv[2]) {
  console.error('usage: node tools/gen-rpg-content.mjs <path-to-cyberpunkish>');
  process.exit(1);
}
const load = (rel) => import(pathToFileURL(join(protoRoot, rel)).href);
const { QUESTS } = await load('src/rpg/Quests.js');
const { DIALOGUES } = await load('src/rpg/Dialogue.js');
const { LOCATION_DEFS } = await load('src/rpg/Locations.js');

const verbatim = (value) => '@"' + JSON.stringify(value, null, 2).replace(/"/g, '""') + '"';

const cs = `// Generated by tools/gen-rpg-content.mjs from the web prototype's rpg/Quests.js, rpg/Dialogue.js and rpg/Locations.js (${new Date().toISOString().slice(0, 10)}).
// The content is ours now: edit it here. Re-running the tool overwrites this file.
namespace Cypher.Core
{
    /// <summary>
    /// The RPG's written content as JSON, as the prototype's tables are written: the jobs (stages, objectives, branches, outcomes), the conversations (nodes, options,
    /// gates, effects) and the named places. The conditions and effects inside use the grammars of <see cref="RpgConditions"/> and <see cref="RpgEffects"/>; the
    /// quest log and the dialogue runner check every table when it is first read.
    /// </summary>
    public static class RpgContent
    {
        public const string QuestsJson = ${verbatim(QUESTS)};

        public const string DialoguesJson = ${verbatim(DIALOGUES)};

        public const string LocationsJson = ${verbatim(LOCATION_DEFS)};
    }
}
`;
const here = dirname(fileURLToPath(import.meta.url));
const file = join(here, '..', 'Assets', '_Cypher', 'Scripts', 'Core', 'Rpg', 'RpgContent.g.cs');
writeFileSync(file, cs);
console.log(`wrote ${QUESTS.length} quests, ${DIALOGUES.length} dialogues and ${LOCATION_DEFS.length} locations to ${file}`);
